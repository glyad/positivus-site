export function authNavigation(section) {
  if (!section) return "";
  const signInCurrent = section === "signin" ? ' aria-current="page"' : "";
  const signUpCurrent = section === "signup" ? ' aria-current="page"' : "";
  return `<nav class="auth-switcher" aria-label="Authentication pages" data-i18n-aria-label="authenticationPages">
    <a href="sign-in.html"${signInCurrent}>${text("signIn")}</a>
    <a href="sign-up.html"${signUpCurrent}>${text("createAccount")}</a>
  </nav>`;
}
