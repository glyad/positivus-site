export const authText = Object.fromEntries(
  Object.entries(copy).map(([key, [en, he]]) => [key, { en, he }])
);

const text = (key) => `<span data-i18n="${key}">${authText[key].en}</span>`;
const icon = (name, className = "") =>
  `<span class="auth-icon auth-icon--${name} ${className}" aria-hidden="true"></span>`;

const field = ({
  id,
  labelKey,
  type = "text",
  placeholderKey,
  autocomplete,
  iconName,
  required = true,
  inputmode,
  maxlength,
  minlength
}) => {
  const describedBy = `${id}-error`;
  const passwordToggle =
    type === "password"
      ? `<button class="auth-control__action" type="button" data-password-toggle data-i18n-aria-label="showPassword" aria-label="Show password">${icon("eye")}</button>`
      : "";

  return `<div class="auth-field" data-field="${id}">
    <label class="auth-field__label" for="${id}">${text(labelKey)}</label>
    <div class="auth-control-wrap">
      ${icon(iconName, "auth-control__leading")}
      <input
        class="auth-control"
        id="${id}"
        name="${id}"
        type="${type}"
        data-i18n-placeholder="${placeholderKey}"
        placeholder="${authText[placeholderKey].en}"
        autocomplete="${autocomplete}"
        aria-describedby="${describedBy}"
        ${required ? "required" : ""}
        ${inputmode ? `inputmode="${inputmode}"` : ""}
        ${maxlength ? `maxlength="${maxlength}"` : ""}
        ${minlength ? `minlength="${minlength}"` : ""}
      />
      ${passwordToggle}
    </div>
    <p class="auth-field__error" id="${describedBy}" data-error-for="${id}"></p>
  </div>`;
};

